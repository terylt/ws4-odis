#!/usr/bin/env python3
"""Build ODIS-Router.md from the files in sections/.

The reading order comes from sections/order.txt, one file name per line.
The output is generated: edit the section files, then re-run

    python3 build.py

and commit the regenerated ODIS-Router.md together with the section changes.
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SECTIONS = HERE / "sections"
OUTPUT = HERE / "ODIS-Router.md"
TITLE = "The ODIS Router"
NOTICE = ("<!-- Generated by build.py from the files in sections/. "
          "Edit those files, not this one, then re-run build.py. -->")
STATUS = ("*Status: draft proposal for discussion. "
          "This document is not part of the ODIS specification.*")


def order():
    names = (SECTIONS / "order.txt").read_text().split()
    return [SECTIONS / name for name in names]


def demote(text):
    """Push every heading down one level so sections nest under the title."""
    out, in_code = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            in_code = not in_code
        elif not in_code and re.match(r"^#+ ", line):
            line = "#" + line
        out.append(line)
    return "\n".join(out)


def heading(text):
    """A section's own title: its first top-level heading."""
    m = re.search(r"^# (.+)$", text, flags=re.MULTILINE)
    return m.group(1).strip() if m else ""


def anchor(title, used):
    """GitHub's anchor for a heading, numbering repeats as GitHub does."""
    slug = re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-")
    n = used.get(slug, 0)
    used[slug] = n + 1
    return slug if n == 0 else f"{slug}-{n}"


def main():
    paths = order()
    texts = [path.read_text().strip() for path in paths]
    titles = [heading(text) for text in texts]

    # The table of contents sits after the first section, the summary.
    marker = "<!-- contents -->"
    parts = [NOTICE, "", f"# {TITLE}", "", STATUS, ""]
    for n, text in enumerate(texts):
        parts.extend([demote(text), ""])
        if n == 0:
            parts.extend(["## Contents", "", marker, ""])
    document = "\n".join(parts)

    # GitHub makes anchors unique across the whole document, so walk every
    # heading in order, outside code blocks, and keep each section's own.
    used, links, in_code = {}, [], False
    wanted = iter(titles)
    target = next(wanted, None)
    for line in document.splitlines():
        if line.startswith("```"):
            in_code = not in_code
            continue
        m = None if in_code else re.match(r"^(#+) (.+)$", line)
        if not m:
            continue
        slug = anchor(m.group(2).strip(), used)
        if len(m.group(1)) == 2 and m.group(2).strip() == target:
            links.append(f"- [{target}](#{slug})")
            target = next(wanted, None)

    OUTPUT.write_text(document.replace(marker, "\n".join(links), 1))
    print(f"wrote {OUTPUT.name} from {len(paths)} sections")


if __name__ == "__main__":
    main()
